"""Build the Chinese edition from the English page without changing its layout."""
from html import escape, unescape
from html.parser import HTMLParser
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
TRANSLATIONS = json.loads((ROOT / 'scripts/translations-zh.json').read_text())
STRINGS = TRANSLATIONS['strings']


class ChinesePage(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.output = []
        self.verbatim = 0
        self.missing = set()
        self.article = None

    def translate(self, value):
        key = value.strip()
        scoped = TRANSLATIONS.get('scoped_strings', {}).get(self.article, {})
        if key in scoped:
            # Chinese clauses around inline emphasis need their own word order
            # and spacing, rather than the English fragment's surrounding spaces.
            return scoped[key]
        if key in STRINGS:
            return value.replace(key, STRINGS[key], 1)
        if re.search('[A-Za-z]', key) and key not in TRANSLATIONS['preserve']:
            self.missing.add(key)
        return value

    def handle_starttag(self, tag, attrs):
        raw = self.get_starttag_text()
        attributes = dict(attrs)
        if tag == 'article':
            self.article = attributes.get('aria-labelledby')
        if tag in ('code', 'script', 'style'):
            self.verbatim += 1
        localizable = {'alt', 'aria-label', 'data-frame-title'}
        if tag == 'meta' and attributes.get('name', attributes.get('property')) in (
            'description', 'og:title', 'og:description', 'og:image:alt'
        ):
            localizable.add('content')
        def attribute(match):
            name, value = match.group(1), match.group(2)
            return f'{name}="{escape(self.translate(unescape(value)), quote=True)}"' if name in localizable else match.group(0)
        raw = re.sub(r'([\w-]+)="([^"]*)"', attribute, raw)
        if tag == 'html':
            raw = raw.replace('lang="en"', 'lang="zh-CN"')
        if tag == 'a' and attributes.get('href') in ('index.html', 'zh.html'):
            raw = raw.replace(' aria-current="page"', '')
            if attributes['href'] == 'zh.html':
                raw = raw[:-1] + ' aria-current="page">'
        if tag == 'meta' and attributes.get('property') == 'og:url':
            raw = raw.replace('https://yh1zzzzzzz.github.io/twinpast/', 'https://yh1zzzzzzz.github.io/twinpast/zh.html')
        if tag == 'script' and attributes.get('src', '').startswith('site.js'):
            self.output.append('<script defer src="locale-zh.js?v=20261115-zh-review"></script>\n  ')
        self.output.append(raw)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)

    def handle_endtag(self, tag):
        if tag == 'article':
            self.article = None
        if tag in ('code', 'script', 'style'):
            self.verbatim -= 1
        self.output.append(f'</{tag}>')

    def handle_data(self, data):
        self.output.append(data if self.verbatim else escape(self.translate(data), quote=False))

    def handle_entityref(self, name):
        self.output.append(f'&{name};')

    def handle_charref(self, name):
        self.output.append(f'&#{name};')

    def handle_decl(self, decl):
        self.output.append(f'<!{decl}>')

    def handle_comment(self, comment):
        self.output.append(f'<!--{comment}-->')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated files without writing them.')
    args = parser.parse_args()
    cases = json.loads((ROOT / 'dist/cases.js').read_text().split(' = ', 1)[1].strip().removesuffix(';'))
    if set(TRANSLATIONS['cases']) != {item['pair_id'] for item in cases}:
        raise SystemExit('Chinese case translations must cover exactly the current video pairs.')
    for item in cases:
        translated = TRANSLATIONS['cases'][item['pair_id']]
        if set(translated) != {'example_label', 'question', 'options'} or len(translated['options']) != len(item['options']):
            raise SystemExit(f"Invalid Chinese case translation: {item['pair_id']}")
    page = ChinesePage()
    page.feed((ROOT / 'dist/index.html').read_text())
    if page.missing:
        raise SystemExit('Missing Chinese translations:\n' + '\n'.join(sorted(page.missing)))
    runtime = {key: TRANSLATIONS[key] for key in ('strings', 'cases')}
    outputs = {
        'zh.html': ''.join(page.output),
        'locale-zh.js': '// Generated by scripts/build_locales.py; edit scripts/translations-zh.json.\n'
        + 'window.TWINPAST_ZH = ' + json.dumps(runtime, ensure_ascii=False, indent=2) + ';\n',
    }
    for name, content in outputs.items():
        path = ROOT / 'dist' / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{name} is out of date. Run npm run build-locales.')
        else:
            path.write_text(content)
    print('Chinese edition is up to date.' if args.check else 'Built zh.html and locale-zh.js.')


if __name__ == '__main__':
    main()
